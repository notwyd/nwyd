#[derive(Debug, Clone, Copy, PartialEq, Eq)]

pub struct Stamp {
    pub kind: i32,
    pub mode: i32,
    pub state: i32,
    pub at: (i32, i32),
    pub facing: i32,
    pub fill: i8,
}

pub fn stamp(window: &mut [i8], zone: (u8, u8), s: &Stamp) -> usize {
    if !(0..KINDS as i32).contains(&s.kind) {
        return 0;
    }

    let Some(slot) = usize::try_from(s.kind * FACINGS as i32 + s.facing)
        .ok()
        .filter(|i| *i < SLOTS)
    else {
        return 0;
    };

    let footprint = &FOOTPRINTS[slot];

    let (ox, oz) = (
        i32::from(zone.0) * super::ZONE_CELLS as i32,
        i32::from(zone.1) * super::ZONE_CELLS as i32,
    );

    let hi = RUNTIME_DIM - 2;

    let mut written = 0;

    for (row, cells) in footprint.iter().enumerate() {
        let local_z = (s.at.1 - ANCHOR + row as i32) - oz;

        'row: for group in 0..(COLS / 3) {
            for n in 0..3 {
                let col = group * 3 + n;

                let local_x = (s.at.0 - ANCHOR + col as i32) - ox;

                if !(local_x > 0 && local_z > 0 && local_x <= hi && local_z <= hi) {
                    break 'row;
                }

                let cell = (local_z * RUNTIME_DIM + local_x) as usize;

                let Some(slot) = window.get_mut(cell) else {
                    break 'row;
                };

                if *slot != IMPASSABLE as i8 && cells[col] != 0 {
                    *slot = s.fill;

                    written += 1;
                }
            }
        }
    }

    written
}
