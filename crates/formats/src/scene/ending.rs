pub fn decrypt(buf: &mut [u8]) {
    for (i, b) in buf.iter_mut().enumerate() {
        *b = b.wrapping_sub(KEY[i % KEY.len()].wrapping_add(i as u8));
    }
}

pub fn encrypt(buf: &mut [u8]) {
    for (i, b) in buf.iter_mut().enumerate() {
        *b = b.wrapping_add(KEY[i % KEY.len()].wrapping_add(i as u8));
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Ending {
    lines: Vec<Option<Vec<u8>>>,
}

pub fn parse(bytes: &[u8]) -> Result<Ending> {
    if bytes.len() != FILE_LEN {
        return Err(Error::structure(
            Kind::Ending,
            format!("expected exactly {FILE_LEN} bytes, file is {}", bytes.len()),
        ));
    }

    let mut buf = bytes.to_vec();

    decrypt(&mut buf);

    let lines = buf
        .chunks_exact(SLOT_LEN)
        .map(|slot| {
            if slot[0] == 0 {
                return None;
            }

            let end = slot.iter().position(|&b| b == 0).unwrap_or(SLOT_LEN);

            Some(slot[..end].to_vec())
        })
        .collect();

    Ok(Ending { lines })
}

impl Ending {
    pub fn len(&self) -> usize {
        self.lines.len()
    }

    pub fn is_empty(&self) -> bool {
        self.lines.is_empty()
    }

    pub fn get(&self, index: usize) -> Option<&[u8]> {
        self.lines.get(index).and_then(Option::as_deref)
    }

    pub fn text(&self, index: usize) -> Option<String> {
        self.get(index)
            .map(|b| codepage::decode(b, Codepage::Windows1252))
    }

    pub fn iter(&self) -> impl Iterator<Item = (usize, &[u8])> {
        self.lines
            .iter()
            .enumerate()
            .filter_map(|(i, l)| l.as_deref().map(|l| (i, l)))
    }

    pub fn occupied(&self) -> usize {
        self.lines.iter().flatten().count()
    }

    pub fn y_of(index: usize) -> i32 {
        index as i32 * LINE_HEIGHT
    }
}
