pub const FIRST_COUNTER: u32 = 1;

pub const CAPE_BODY: i32 = 100;

pub const ID_WINDOWS: [(i32, i32); 2] = [(0x1036, 0x105D), (0x10CC, 0x1193)];

pub const EXTRA_ID_WINDOW: (i32, i32) = (0x189D, 0x1900);

#[derive(Debug, Clone, Copy, PartialEq, Eq)]

pub struct Costume {
    pub body: i32,
    pub model: u32,
    pub colour: u8,
}

pub fn body_substitution(body: i32, parts: usize) -> Vec<Option<PartNames>> {
    let mut counter = FIRST_COUNTER;

    let mut out = Vec::with_capacity(parts);

    for _ in 0..parts {
        match part_names(body, counter) {
            Some(row) => {
                counter = row.next;

                out.push(Some(row));
            }
            None => out.push(None),
        }
    }

    out
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]

pub struct PartNames {
    pub texture: Option<&'static str>,
    pub mesh: Option<&'static str>,
    pub next: u32,
}

pub fn body_for(costume: i32, face: i32, cape_side: u8) -> Costume {
    let decade = face / 10;

    match costume {
        0x110E => match (decade == 1 || decade == 3, cape_side) {
            (false, 1) => Costume {
                body: 0xA8,
                model: 0,
                colour: 9,
            },
            (false, 2) => Costume {
                body: 0xA7,
                model: 0,
                colour: 9,
            },
            (true, 1) => Costume {
                body: 0xAB,
                model: 1,
                colour: 9,
            },
            (true, 2) => Costume {
                body: 0xAA,
                model: 1,
                colour: 9,
            },
            _ => Costume {
                body: 0,
                model: 0,
                colour: 0,
            },
        },
        0x110F => {
            let model = u32::from(decade == 1 || decade == 3);

            let body = match cape_side {
                1 => 0xB4,
                2 => 0xB6,
                _ => 0xB8,
            };

            Costume {
                body: body + model as i32,
                model,
                colour: 9,
            }
        }
        id => match CASES.binary_search_by_key(&id, |&(c, ..)| i32::from(c)) {
            Ok(i) => {
                let (_, body, model, colour) = CASES[i];

                Costume {
                    body: i32::from(body),
                    model: u32::from(model),
                    colour,
                }
            }
            Err(_) => Costume {
                body: id - 0x105C,
                model: (id % 2) as u32,
                colour: 9,
            },
        },
    }
}

pub fn part_names(body: i32, counter: u32) -> Option<PartNames> {
    let key = (i16::try_from(body).ok()?, u8::try_from(counter).ok()?);

    let i = NAMES
        .binary_search_by_key(&key, |&(b, c, ..)| (b, c))
        .ok()?;

    let (_, _, texture, mesh, next) = NAMES[i];

    Some(PartNames {
        texture: (!texture.is_empty()).then_some(texture),
        mesh: (!mesh.is_empty()).then_some(mesh),
        next: u32::from(next),
    })
}

