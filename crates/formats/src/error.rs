#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error("{kind} file is truncated: needed {needed} bytes at offset {offset}, file is {len}")]
    Truncated {
        kind: Kind,
        offset: usize,
        needed: usize,
        len: usize,
    },
    #[error("{kind} file has bad magic: expected {expected:?}, found {found:02x?}")]
    BadMagic {
        kind: Kind,
        expected: &'static str,
        found: [u8; 4],
    },
    #[error("{kind}: {0}", kind = Kind::Wys)]
    Wys(String),
    #[error("{kind}: {0}", kind = Kind::Wyt)]
    Wyt(String),
    #[error("{kind}: {0}", kind = Kind::Wyp)]
    Wyp(String),
    #[error("{kind}: {message}")]
    Structure { kind: Kind, message: String },
    #[error("png decode failed: {0}")]
    Png(#[from] png::DecodingError),
}

impl Error {
    pub fn structure(kind: Kind, message: impl Into<String>) -> Self {
        Error::Structure {
            kind,
            message: message.into(),
        }
    }
}
