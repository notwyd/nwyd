pub fn to_next(level: u16, transcendent: bool) -> Option<i64> {
    let table: &[i64] = match transcendent {
        true => &TRANSCENDENT,
        false => &NORMAL,
    };

    table.get(usize::from(level)).copied()
}

pub fn level_span(level: u16, transcendent: bool) -> Option<(i64, i64)> {
    let high = to_next(level, transcendent)?;

    let low = match level.checked_sub(1) {
        Some(previous) => to_next(previous, transcendent)?,
        None => 0,
    };

    Some((low, high))
}
